-- 1. 项目台账主表
CREATE TABLE OM4_PROJECT
(
	ID VARCHAR2(64) NOT NULL,
	PROJECT_CODE VARCHAR2(64) NOT NULL,
	PROJECT_NAME NVARCHAR2(300) NOT NULL,
	CAT NVARCHAR2(64),
	DISTRICT NVARCHAR2(64),
	OWNER NVARCHAR2(300),
	ADDRESS NVARCHAR2(500),
	COST NUMBER(14,2),
	SCALE NVARCHAR2(100),
	SCALE_UNIT NVARCHAR2(32),
	DAYS NUMBER(6),
	START_DATE VARCHAR2(10),
	END_DATE VARCHAR2(10),
	BUILD_STATUS NVARCHAR2(16) DEFAULT '未开工',
	SUPERVISE NVARCHAR2(200),
	LNG VARCHAR2(32),
	LAT VARCHAR2(32),
	CRS NVARCHAR2(64),
	SPATIAL NVARCHAR2(1000),
	SYNC_AT VARCHAR2(32),
	RISK_LEVEL CHAR(1),
	SCORE_TOTAL NUMBER(4),
	INSPECT_SCORE NUMBER(4) DEFAULT 0,
	SIDE_COUNT NUMBER(4) DEFAULT 0,
	ACCEPT_COUNT NUMBER(4) DEFAULT 0,
	COMPLETENESS NUMBER(4) DEFAULT 0,
	REVIEW_JSON CLOB,
	REVIEW_SRC VARCHAR2(16),
	REVIEW_BY NVARCHAR2(64),
	REVIEW_TIME VARCHAR2(32),
	STATUS CHAR(1) DEFAULT '0' NOT NULL,
	CREATE_BY VARCHAR2(64) NOT NULL,
	CREATE_DATE TIMESTAMP NOT NULL,
	UPDATE_BY VARCHAR2(64) NOT NULL,
	UPDATE_DATE TIMESTAMP NOT NULL,
	REMARKS NVARCHAR2(500),
	CORP_CODE VARCHAR2(64) DEFAULT '0' NOT NULL,
	CORP_NAME NVARCHAR2(100),
	PRIMARY KEY (ID)
);
CREATE UNIQUE INDEX UK_OM4_PROJECT_CODE ON OM4_PROJECT(PROJECT_CODE);
CREATE INDEX IDX_OM4_PROJ_DISTRICT ON OM4_PROJECT(DISTRICT);
CREATE INDEX IDX_OM4_PROJ_CAT ON OM4_PROJECT(CAT);
CREATE INDEX IDX_OM4_PROJ_STATUS ON OM4_PROJECT(BUILD_STATUS);
CREATE INDEX IDX_OM4_PROJ_RISK ON OM4_PROJECT(RISK_LEVEL);
COMMENT ON TABLE OM4_PROJECT IS '市政安全一张图-项目台账主表';
